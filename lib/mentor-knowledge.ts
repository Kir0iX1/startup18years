const fallbackAnswer = `Давай конкретизирую под тебя. Подскажи три вещи:

- **Сколько времени** в неделю ты готов уделять — 5, 15 или 30+ часов?
- **Что уже получается** лучше других — тексты, картинки, общение, техника, организация?
- **Какая цель** на 3 месяца — первые 10 тыс. ₽ или стабильные 40+?

Пока можешь пройти тест на профиль ниже — он подберёт 2–3 направления, а я помогу выстроить план под них.`

function normalize(text: string) {
  return text.toLowerCase().replace(/ё/g, 'е')
}

export function getOfflineAnswer(question: string): string {
  const q = normalize(question)
  let best: Topic | null = null
  let bestScore = 0

  for (const topic of topics) {
    let score = 0
    for (const kw of topic.keywords) {
      if (q.includes(normalize(kw))) score += kw.length * (topic.weight ?? 1)
    }
    if (score > bestScore) {
      bestScore = score
      best = topic
    }
  }

  return best ? best.answer : fallbackAnswer
}
